_RADIO_TIERRA_KM = 6371.0


def _haversine_km(lat1: float, lon1: float, lat2: float, lon2: float) -> float:
    p1, p2 = math.radians(lat1), math.radians(lat2)
    dphi = math.radians(lat2 - lat1)
    dlambda = math.radians(lon2 - lon1)
    a = math.sin(dphi / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(dlambda / 2) ** 2
    return 2 * _RADIO_TIERRA_KM * math.asin(math.sqrt(a))


def distancia_general_paz_km(lat: float | None, lon: float | None) -> float | None:
    """Distancia minima (km) desde (lat, lon) hasta el punto mas cercano
    de la traza de la General Paz. None si no hay coordenadas."""
    if lat is None or lon is None:
        return None
    return min(_haversine_km(lat, lon, plat, plon) for plat, plon in GENERAL_PAZ)
